import { chromium } from '@playwright/test';
const url = process.argv[2];
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = [];
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
p.on('pageerror', (e) => errs.push('pageerror ' + e.message));
const resp = await p.goto(url, { waitUntil: 'networkidle' });
console.log('xrobots', resp.headers()['x-robots-tag']);
console.log('meta', await p.locator('meta[name=robots]').getAttribute('content'));
await p.screenshot({ path: 'test-results/deployed/landing.png' });
const btn = p.getByRole('button', { name: 'Play the bot' });
await btn.waitFor(); await p.getByLabel('Your name').fill('Smoke'); await btn.click();
await p.waitForTimeout(5000);
console.log('url', p.url());
await p.screenshot({ path: 'test-results/deployed/setup.png' });
console.log('body', (await p.innerText('body')).slice(0, 300).replace(/\n/g, ' | '));
console.log('errors', JSON.stringify(errs));
await b.close();
